void psx_configure(const PSX_CONFIG *config)
{
    if (config == NULL)
        return;
    psx_config = *config;
    psx_quit = 0;
    psx_pad_buttons = 0;
    if (psx_config.window_title == NULL)
        psx_config.window_title = "PlayStation";
    if (psx_config.window_width <= 0)
        psx_config.window_width = PSX_DEFAULT_WINDOW_WIDTH;
    if (psx_config.window_height <= 0)
        psx_config.window_height = PSX_DEFAULT_WINDOW_HEIGHT;
    if (psx_config.refresh_rate <= 0)
        psx_config.refresh_rate = PSX_DEFAULT_REFRESH_RATE;
#if defined(_WIN32)
    psx_window_width = psx_config.window_width;
    psx_window_height = psx_config.window_height;
#endif
    psx_headless = psx_config.headless != 0;
}

