void PsyQPadPublishDigital(int port, int connected, uint16_t active_low_buttons)
{
    uint8_t *packet;
    int index = (port & 0x10) != 0;
    if (!pad_running || pad_buffers[index] == 0)
        return;
    packet = pad_buffers[index];
    if (!connected)
    {
        memset(packet, 0xff, 8);
        return;
    }
    packet[0] = 0;
    packet[1] = 0x41;
    packet[2] = (uint8_t)active_low_buttons;
    packet[3] = (uint8_t)(active_low_buttons >> 8);
}

enum
{
    SPU_MASTER_VOLUME_LEFT = 0x180,
    SPU_MASTER_VOLUME_RIGHT = 0x182,
    SPU_KEY_ON_LOW = 0x188,
    SPU_KEY_ON_HIGH = 0x18a,
    SPU_KEY_OFF_LOW = 0x18c,
    SPU_KEY_OFF_HIGH = 0x18e,
    SPU_END_FLAGS_LOW = 0x19c,
    SPU_END_FLAGS_HIGH = 0x19e
};

volatile uint16_t VOICE_00_LEFT_RIGHT[PSYQ_SPU_REGISTER_BYTES / 2];

#if defined(_WIN32)
static CRITICAL_SECTION psyq_spu_lock;
static sint32 psyq_spu_lock_initialized;

static void psyq_spu_lock_enter(void)
{
    if (psyq_spu_lock_initialized)
        EnterCriticalSection(&psyq_spu_lock);
}

static void psyq_spu_lock_leave(void)
{
    if (psyq_spu_lock_initialized)
        LeaveCriticalSection(&psyq_spu_lock);
}
#else
static void psyq_spu_lock_enter(void) {}
static void psyq_spu_lock_leave(void) {}
#endif

static uint16_t register_read(uint32_t byte_offset)
{
    if ((byte_offset & 1u) != 0 || byte_offset >= PSYQ_SPU_REGISTER_BYTES)
        return 0;
    return VOICE_00_LEFT_RIGHT[byte_offset >> 1];
}

static void register_write(uint32_t byte_offset, uint16_t value)
{
    if ((byte_offset & 1u) == 0 && byte_offset < PSYQ_SPU_REGISTER_BYTES)
        VOICE_00_LEFT_RIGHT[byte_offset >> 1] = value;
}

void PsyQSpuInit(void)
{
#if defined(_WIN32)
    if (!psyq_spu_lock_initialized)
    {
        InitializeCriticalSection(&psyq_spu_lock);
        psyq_spu_lock_initialized = 1;
    }
#endif
    psyq_spu_lock_enter();
    memset((void *)VOICE_00_LEFT_RIGHT, 0, sizeof(VOICE_00_LEFT_RIGHT));
    spu_core_init();
    psyq_spu_lock_leave();
}

void PsyQSpuShutdown(void)
{
    psyq_spu_lock_enter();
    spu_core_shutdown();
    memset((void *)VOICE_00_LEFT_RIGHT, 0, sizeof(VOICE_00_LEFT_RIGHT));
    psyq_spu_lock_leave();
#if defined(_WIN32)
    if (psyq_spu_lock_initialized)
    {
        DeleteCriticalSection(&psyq_spu_lock);
        psyq_spu_lock_initialized = 0;
    }
#endif
}

void PsyQSpuSyncVoice(int voice)
{
    uint32_t offset;
    SPU_voice_registers registers;
    if (voice < 0 || voice >= PSYQ_SPU_VOICE_COUNT)
        return;
    psyq_spu_lock_enter();
    offset = (uint32_t)voice * 0x10u;
    registers.volume_left = (int16_t)register_read(offset + 0x0);
    registers.volume_right = (int16_t)register_read(offset + 0x2);
    registers.pitch = register_read(offset + 0x4);
    registers.start_address = register_read(offset + 0x6);
    registers.adsr1 = register_read(offset + 0x8);
    registers.adsr2 = register_read(offset + 0xa);
    registers.repeat_address = register_read(offset + 0xe);
    spu_core_set_voice_registers(voice, &registers);
    psyq_spu_lock_leave();
}

void PsyQSpuSyncAllVoices(void)
{
    int voice;
    psyq_spu_lock_enter();
    for (voice = 0; voice < PSYQ_SPU_VOICE_COUNT; ++voice)
        PsyQSpuSyncVoice(voice);
    spu_core_set_master_volume((int16_t)register_read(SPU_MASTER_VOLUME_LEFT),
                               (int16_t)register_read(SPU_MASTER_VOLUME_RIGHT));
    psyq_spu_lock_leave();
}

void PsyQSpuKeyOn(uint32_t voice_mask)
{
    uint32_t mask = voice_mask & 0x00ffffffu;
    int voice;
    psyq_spu_lock_enter();
    register_write(SPU_KEY_ON_LOW, (uint16_t)mask);
    register_write(SPU_KEY_ON_HIGH, (uint16_t)(mask >> 16));
    for (voice = 0; voice < PSYQ_SPU_VOICE_COUNT; ++voice)
        if ((mask & (1u << voice)) != 0)
            PsyQSpuSyncVoice(voice);
    spu_core_key_on(mask);
    psyq_spu_lock_leave();
}

void PsyQSpuKeyOff(uint32_t voice_mask)
{
    uint32_t mask = voice_mask & 0x00ffffffu;
    psyq_spu_lock_enter();
    register_write(SPU_KEY_OFF_LOW, (uint16_t)mask);
    register_write(SPU_KEY_OFF_HIGH, (uint16_t)(mask >> 16));
    spu_core_key_off(mask);
    psyq_spu_lock_leave();
}

