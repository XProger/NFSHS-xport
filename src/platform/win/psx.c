uint32 *ClearOTagR(uint32 *ot, sint32 count)
{
    sint32 index;
    if (psx_config.host.clear_ot != NULL)
        return psx_config.host.clear_ot(psx_config.host_user, ot, count, 1);
    if (ot == NULL || count <= 0)
        return ot;
    ot[0] = 0x00ffffff;
    for (index = 1; index < count; ++index)
        ot[index] = (uint32)(intptr)&ot[index - 1] & 0x00ffffff;
    return ot;
}

uint32 *ClearOTag(uint32 *ot, sint32 count)
{
    sint32 index;
    if (psx_config.host.clear_ot != NULL)
        return psx_config.host.clear_ot(psx_config.host_user, ot, count, 0);
    if (ot == NULL || count <= 0)
        return ot;
    for (index = 0; index + 1 < count; ++index)
        ot[index] = (uint32)(intptr)&ot[index + 1] & 0x00ffffff;
    ot[count - 1] = 0x00ffffff;
    return ot;
}

