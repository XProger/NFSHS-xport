void PsyQSpuRender(int16_t *interleaved_stereo, uint32_t frame_count)
{
    uint32_t flags;
    int voice;
    psyq_spu_lock_enter();
    PsyQSpuSyncAllVoices();
    spu_core_render(interleaved_stereo, frame_count);
    flags = spu_core_end_flags();
    register_write(SPU_END_FLAGS_LOW, (uint16_t)flags);
    register_write(SPU_END_FLAGS_HIGH, (uint16_t)(flags >> 16));
    for (voice = 0; voice < PSYQ_SPU_VOICE_COUNT; ++voice)
        register_write((uint32_t)voice * 0x10u + 0xcu, spu_core_voice_envelope(voice));
    psyq_spu_lock_leave();
}

void PsyQSpuAdvance(uint32_t frame_count)
{
    int16_t discarded[256 * 2];
    while (frame_count != 0)
    {
        uint32_t block = frame_count < 256u ? frame_count : 256u;
        PsyQSpuRender(discarded, block);
        frame_count -= block;
    }
}

uint16_t PsyQSpuReadRegister(uint32_t byte_offset)
{
    uint16_t value;
    psyq_spu_lock_enter();
    value = register_read(byte_offset);
    psyq_spu_lock_leave();
    return value;
}

void PsyQSpuWriteRegister(uint32_t byte_offset, uint16_t value)
{
    psyq_spu_lock_enter();
    register_write(byte_offset, value);
    if (byte_offset < 0x180u)
        PsyQSpuSyncVoice((int)(byte_offset >> 4));
    else if (byte_offset == SPU_MASTER_VOLUME_LEFT || byte_offset == SPU_MASTER_VOLUME_RIGHT)
        spu_core_set_master_volume((int16_t)register_read(SPU_MASTER_VOLUME_LEFT),
                                   (int16_t)register_read(SPU_MASTER_VOLUME_RIGHT));
    psyq_spu_lock_leave();
}
