    bitmap.bmiHeader.biCompression = BI_RGB;
    output_width = psx_window_height * width / height;
    output_x = (psx_window_width - output_width) / 2;
    device = GetDC(psx_window);
    StretchDIBits(device, output_x, 0, output_width, psx_window_height, 0, 0, width, height, pixels, &bitmap, DIB_RGB_COLORS, SRCCOPY);
    ReleaseDC(psx_window, device);
    if (title != NULL)
        SetWindowText(psx_window, title);
    return 1;
#else
    (void)pixels;
    (void)width;
    (void)height;
    (void)title;
