uint16_t PsyQ_gpu_vram[PSYQ_GPU_VRAM_WIDTH * PSYQ_GPU_VRAM_HEIGHT];

void PsyQGpuResetVram(void)
{
    memset(PsyQ_gpu_vram, 0, sizeof(PsyQ_gpu_vram));
}

int PsyQGpuClearImage(int x, int y, int width, int height,
                                  uint8_t red, uint8_t green, uint8_t blue)
{
    uint16_t color;
    int row;
    int column;
    if (width < 0 || height < 0)
        return -1;
    color = (uint16_t)((red >> 3) | ((green >> 3) << 5) | ((blue >> 3) << 10));
    for (row = 0; row < height; ++row)
        for (column = 0; column < width; ++column)
            if ((unsigned int)(x + column) < PSYQ_GPU_VRAM_WIDTH &&
                (unsigned int)(y + row) < PSYQ_GPU_VRAM_HEIGHT)
                PsyQ_gpu_vram[(y + row) * PSYQ_GPU_VRAM_WIDTH + x + column] = color;
    return 0;
}

int PsyQGpuLoadImage(int x, int y, int width, int height, const uint16_t *pixels)
{
    int row;
    int column;
    if (pixels == 0 || width < 0 || height < 0)
        return -1;
    for (row = 0; row < height; ++row)
        for (column = 0; column < width; ++column)
        {
            uint16_t value = *pixels++;
            if ((unsigned int)(x + column) < PSYQ_GPU_VRAM_WIDTH &&
                (unsigned int)(y + row) < PSYQ_GPU_VRAM_HEIGHT)
                PsyQ_gpu_vram[(y + row) * PSYQ_GPU_VRAM_WIDTH + x + column] = value;
        }
    return 0;
}

int PsyQGpuStoreImage(int x, int y, int width, int height, uint16_t *pixels)
{
    int row;
    int column;
    if (pixels == 0 || width < 0 || height < 0)
        return -1;
    for (row = 0; row < height; ++row)
        for (column = 0; column < width; ++column)
            *pixels++ = PsyQ_gpu_vram[((unsigned int)(y + row) & (PSYQ_GPU_VRAM_HEIGHT - 1)) *
                                      PSYQ_GPU_VRAM_WIDTH +
                                      ((unsigned int)(x + column) & (PSYQ_GPU_VRAM_WIDTH - 1))];
    if ((width * height) & 1)
        *pixels = 0;
    return 0;
}

int PsyQGpuMoveImage(int x, int y, int width, int height,
                                 int destination_x, int destination_y)
{
    int row;
    if (width < 0 || height < 0 || x < 0 || y < 0 || destination_x < 0 || destination_y < 0 ||
        x + width > PSYQ_GPU_VRAM_WIDTH || y + height > PSYQ_GPU_VRAM_HEIGHT ||
        destination_x + width > PSYQ_GPU_VRAM_WIDTH || destination_y + height > PSYQ_GPU_VRAM_HEIGHT)
        return -1;
    if (destination_y > y)
        for (row = height - 1; row >= 0; --row)
            memmove(PsyQ_gpu_vram + (destination_y + row) * PSYQ_GPU_VRAM_WIDTH + destination_x,
                    PsyQ_gpu_vram + (y + row) * PSYQ_GPU_VRAM_WIDTH + x,
                    (size_t)width * sizeof(uint16_t));
    else
        for (row = 0; row < height; ++row)
            memmove(PsyQ_gpu_vram + (destination_y + row) * PSYQ_GPU_VRAM_WIDTH + destination_x,
                    PsyQ_gpu_vram + (y + row) * PSYQ_GPU_VRAM_WIDTH + x,
                    (size_t)width * sizeof(uint16_t));
    return 0;
}

