static void matrix_identity(MATRIX *m)
{
    memset(m, 0, sizeof(*m));
    m->m[0][0] = m->m[1][1] = m->m[2][2] = ONE;
}

static void matrix_left_multiply(MATRIX *m, const MATRIX *left)
{
    MATRIX out;
    sint32 r, c;
    memset(&out, 0, sizeof(out));
    for (r = 0; r < 3; r++)
        for (c = 0; c < 3; c++)
            out.m[r][c] = (sint16)mac_shift12((sint64)left->m[r][0] * m->m[0][c] + (sint64)left->m[r][1] * m->m[1][c] + (sint64)left->m[r][2] * m->m[2][c]);
    out.t[0] = m->t[0];
    out.t[1] = m->t[1];
    out.t[2] = m->t[2];
    *m = out;
}

MATRIX *RotMatrixYXZ(SVECTOR *r, MATRIX *m)
{
    MATRIX a;
    sint32 c, s;
    if (!r || !m)
        return m;
    matrix_identity(m);
    c = psx_fixed_cos(r->vy);
    s = psx_fixed_sin(r->vy);
    matrix_identity(&a);
    a.m[0][0] = (sint16)c;
    a.m[0][2] = (sint16)s;
    a.m[2][0] = (sint16)-s;
    a.m[2][2] = (sint16)c;
    matrix_left_multiply(m, &a);
    c = psx_fixed_cos(r->vx);
    s = psx_fixed_sin(r->vx);
    matrix_identity(&a);
    a.m[1][1] = (sint16)c;
    a.m[1][2] = (sint16)-s;
    a.m[2][1] = (sint16)s;
    a.m[2][2] = (sint16)c;
    matrix_left_multiply(m, &a);
    c = psx_fixed_cos(r->vz);
    s = psx_fixed_sin(r->vz);
    matrix_identity(&a);
    a.m[0][0] = (sint16)c;
    a.m[0][1] = (sint16)-s;
    a.m[1][0] = (sint16)s;
    a.m[1][1] = (sint16)c;
    matrix_left_multiply(m, &a);
    return m;
}

/* PsyQ RotMatrix order, carried over from de-NFS4's host runtime. */
MATRIX *RotMatrix(SVECTOR *r, MATRIX *m)
{
    sint32 sx, cx, sy, cy, sz, cz, nsy, czn, szn;
    if (!r || !m)
        return m;
    sx = psx_fixed_sin(r->vx);
    cx = psx_fixed_cos(r->vx);
    sy = psx_fixed_sin(r->vy);
    cy = psx_fixed_cos(r->vy);
    sz = psx_fixed_sin(r->vz);
    cz = psx_fixed_cos(r->vz);
    nsy = -sy;
    m->m[0][2] = (sint16)sy;
    m->m[1][2] = (sint16)(-((cy * sx) >> 12));
    m->m[2][2] = (sint16)((cy * cx) >> 12);
    m->m[0][0] = (sint16)((cz * cy) >> 12);
    m->m[0][1] = (sint16)(-((sz * cy) >> 12));
    czn = (cz * nsy) >> 12;
    m->m[1][0] = (sint16)((sz * cx) >> 12) - (sint16)((czn * sx) >> 12);
    m->m[2][0] = (sint16)((sz * sx) >> 12) + (sint16)((czn * cx) >> 12);
    szn = (sz * nsy) >> 12;
    m->m[1][1] = (sint16)((cz * cx) >> 12) + (sint16)((szn * sx) >> 12);
    m->m[2][1] = (sint16)((cz * sx) >> 12) - (sint16)((szn * cx) >> 12);
    return m;
}

MATRIX *TransMatrix(MATRIX *m, VECTOR *v)
{
    if (m && v)
    {
        m->t[0] = v->vx;
        m->t[1] = v->vy;
        m->t[2] = v->vz;
    }
    return m;
}

MATRIX *ScaleMatrix(MATRIX *m, VECTOR *v)
{
    sint32 r;
    if (m && v)
        for (r = 0; r < 3; r++)
        {
            m->m[r][0] = (sint16)mac_shift12((sint64)m->m[r][0] * v->vx);
            m->m[r][1] = (sint16)mac_shift12((sint64)m->m[r][1] * v->vy);
            m->m[r][2] = (sint16)mac_shift12((sint64)m->m[r][2] * v->vz);
        }
    return m;
}

/* PsyQ matrix helpers used by FUN_80092194.  MulMatrix0 multiplies only the
 * 3x3 rotation members; the caller computes the translated origin with
 * ApplyMatrixLV exactly as the original game does. */
MATRIX *MulMatrix0(MATRIX *m0, MATRIX *m1, MATRIX *m2)
{
    MATRIX out;
    sint32 row, column;
    if (!m0 || !m1 || !m2)
        return m2;
    memset(&out, 0, sizeof(out));
    for (row = 0; row < 3; row++)
        for (column = 0; column < 3; column++)
            out.m[row][column] = (sint16)mac_shift12((sint64)m0->m[row][0] * m1->m[0][column] + (sint64)m0->m[row][1] * m1->m[1][column] + (sint64)m0->m[row][2] * m1->m[2][column]);
    *m2 = out;
    return m2;
}

MATRIX *ScaleMatrixL(MATRIX *m, VECTOR *v)
{
    return ScaleMatrix(m, v);
}

void psx_gte_transform(const SVECTOR *v, VECTOR *out, sint32 *flag)
{
    VECTOR q;
    gte.flag = 0;
    transform(&gte.rotation, v, &q, 1);
    out->vx = clamp_ir(q.vx, 1UL << 24);
    out->vy = clamp_ir(q.vy, 1UL << 23);
    out->vz = clamp_ir(q.vz, 1UL << 22);
    out->pad = 0;
    finish_flag();
    if (flag)
        *flag = gte.flag;
}

sint32 psx_gte_project(const SVECTOR *v, sint32 *sxy, sint32 *flag)
{
    VECTOR q;
    uint32 depth, quotient;
    sint32 ix, iy, sx, sy;
    gte.flag = 0;
    transform(&gte.rotation, v, &q, 1);
    ix = clamp_ir(q.vx, 1UL << 24);
    iy = clamp_ir(q.vy, 1UL << 23);
    clamp_ir(q.vz, 1UL << 22);
    depth = clamp_sz(q.vz);
    if (!depth || (uint32)gte.h >= depth * 2UL)
    {
        quotient = 0x1ffffUL;
        gte.flag |= 1L << 17;
    }
    else
    {
        quotient = (uint32)(((uint64)gte.h << 16) / depth);
        if (quotient > 0x1ffffUL)
            quotient = 0x1ffffUL;
    }
    sx = clamp_sxy(gte.ofx + (sint32)(((sint64)ix * quotient) >> 16), 1UL << 14);
    sy = clamp_sxy(gte.ofy + (sint32)(((sint64)iy * quotient) >> 16), 1UL << 13);
    gte.sxy[0] = gte.sxy[1];
    gte.sxy[1] = gte.sxy[2];
    gte.sxy[2] = (sint32)((uint16)sx | ((uint32)(uint16)sy << 16));
    gte.sz[0] = gte.sz[1];
    gte.sz[1] = gte.sz[2];
    gte.sz[2] = gte.sz[3];
    gte.sz[3] = depth;
    finish_flag();
    if (sxy)
        *sxy = gte.sxy[2];
    if (flag)
        *flag = gte.flag;
    return (sint32)(depth >> 2);
}

